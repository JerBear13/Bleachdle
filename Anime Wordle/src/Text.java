public class Text {
    String text;
    int x;
    int y;

    public Text(String T, int X, int Y) {
        text = T;
        x = X;
        y = Y;
    }

    public String getText() {
        return text;
    }

    public int getX() {
        return x;
    }

    public int getY() {
        return y;
    }

}
